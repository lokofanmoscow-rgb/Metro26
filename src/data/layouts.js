// Система координат — как у поезда: x вправо по ходу, наш путь x = 0, края платформ — в 1,48 м от оси пути.
// d0 — по порядку станций в LINES (по ходу «от начала линии»), d1 — в обратную сторону.
//  tr: [x, вид, линия]: me — наш путь; rev — наш встречный; oth — путь другой линии, поезда идут
//      в ту же сторону (кросс-платформенная пересадка); otr — другой линии навстречу; svc — без пассажиров
//  pl: [x0, x1] — платформы; door — сторона дверей (если платформы с обеих сторон пути)
//  cols — ряды колонн: mid — между путями; edge — у краёв платформ; isl — по краям островных платформ;
//         alex — «Александровский сад» (ряд между путями и по ряду в середине платформ)
//  hall — стены зала [слева, справа]; glass — остеклённая путевая стена (L/R)
const side = (S, W, cols = 'mid') => ({ tr: [[0, 'me'], [-S, 'rev']], pl: [[1.48, 1.48 + W], [-S - 1.48 - W, -S - 1.48]], cols });
const isl = (x, line, W = null) => ({ tr: [[0, 'me'], [x, 'oth', line]], pl: [x > 0 ? [1.48, x - 1.48] : [x + 1.48, -1.48]], W });
const both = (L) => ({ d0: L, d1: L });

